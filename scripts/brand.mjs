#!/usr/bin/env node
// Brand this app: product name, colors, logo, theme and font, from one place (brand.json at the repo root).
//
//   node scripts/brand.mjs                                   print the current brand
//   node scripts/brand.mjs --name "Acme Booking" [--primary "#2563eb"] [--accent "#f97316"]
//        [--logo path/to/logo.svg|.png|default] [--theme light|dark|auto] [--font "<css font stack>"] [--dry-run]
//   node scripts/brand.mjs --apply                           re-apply brand.json after editing it by hand
//
// What it writes (re-runnable, idempotent):
//   brand.json                       the source of truth. The web bundle imports it and the server uses its name
//                                    for email and calendar text unless APP_NAME is set.
//   public/assets/app.css            only the block between "brand:start" and "brand:end" (CSS custom properties).
//   public/assets/logo.svg|png       the given logo, or the default logo drawn in the brand colors.
//   public/index.html, public/static/*.html   product name, logo links and theme-color meta tags.
// Run `npm run build` afterwards so the web bundle and server pick up the new brand.json.
import { copyFileSync, existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, extname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const BRAND_FILE = join(ROOT, "brand.json");
const CSS_FILE = join(ROOT, "public", "assets", "app.css");
const ASSETS = join(ROOT, "public", "assets");
const INDEX_HTML = join(ROOT, "public", "index.html");
const STATIC_DIR = join(ROOT, "public", "static");
const START = "/* brand:start (generated by scripts/brand.mjs; do not edit by hand) */";
const END = "/* brand:end */";
const THEMES = ["light", "dark", "auto"];
const LOGO_EXTS = [".svg", ".png"];
const DEFAULT_LOGO = "/assets/logo.svg";

const argv = process.argv.slice(2);
const KNOWN = ["name", "primary", "accent", "logo", "theme", "font"];
const BOOL = ["dry-run", "apply", "help"];

function fail(msg) {
  process.stderr.write(`brand: ${msg}\n`);
  process.exit(2);
}

function parseArgs() {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith("--")) fail(`unexpected argument ${JSON.stringify(a)}`);
    const k = a.slice(2);
    if (BOOL.includes(k)) out[k] = true;
    else if (KNOWN.includes(k)) {
      const v = argv[++i];
      if (v === undefined) fail(`--${k} needs a value`);
      out[k] = v;
    } else fail(`unknown option --${k}`);
  }
  return out;
}

// ---------- colors ----------
function normHex(v, flag) {
  const m = /^#?([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(String(v).trim());
  if (!m) fail(`--${flag} must be a hex color like #2563eb`);
  let h = m[1].toLowerCase();
  if (h.length === 3) h = [...h].map((c) => c + c).join("");
  return `#${h}`;
}
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const hex = (c) => `#${c.map((x) => Math.round(Math.max(0, Math.min(255, x))).toString(16).padStart(2, "0")).join("")}`;
/** t = share of `a` in the result. */
const mix = (a, b, t) => hex(rgb(a).map((x, i) => x * t + rgb(b)[i] * (1 - t)));
function luminance(h) {
  const [r, g, b] = rgb(h).map((x) => {
    const c = x / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
function contrast(a, b) {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}
/** Move `c` toward `toward` until it reaches 4.5:1 against `bg` (text that must stay readable). */
function readable(c, bg, toward) {
  for (let t = 1; t >= 0; t -= 0.05) {
    const m = mix(c, toward, t);
    if (contrast(m, bg) >= 4.5) return m;
  }
  return toward;
}

// Neutral palettes. The light one is the original Slotwise look.
const LIGHT = {
  "--ink": "#17212b",
  "--ink-2": "#4b5866",
  "--muted": "#6b7785",
  "--faint": "#9aa4ae",
  "--line": "#e2e6ea",
  "--field-line": "#cfd5db",
  "--bg": "#f6f7f8",
  "--card": "#ffffff",
  "--subtle": "#fafbfc",
  "--chip-bg": "#eef0f3",
  "--danger": "#b42318",
  "--danger-bg": "#fef3f2",
  "--danger-line": "#fecdca",
  "--ok": "#067647",
  "--ok-bg": "#ecfdf3",
  "--ok-line": "#abefc6",
  "--warn": "#93370d",
  "--warn-bg": "#fffaeb",
  "--warn-line": "#fedf89",
  "--shadow": "0 1px 2px rgba(16, 24, 40, 0.06), 0 6px 24px rgba(16, 24, 40, 0.08)",
};
const DARK = {
  "--ink": "#e6e9ec",
  "--ink-2": "#b8c1ca",
  "--muted": "#8f9aa6",
  "--faint": "#5d6874",
  "--line": "#2b333b",
  "--field-line": "#3b4550",
  "--bg": "#0f1418",
  "--card": "#171d23",
  "--subtle": "#1c232a",
  "--chip-bg": "#242c34",
  "--danger": "#f97066",
  "--danger-bg": "#2c1513",
  "--danger-line": "#5a2420",
  "--ok": "#47cd89",
  "--ok-bg": "#0d2619",
  "--ok-line": "#1d5236",
  "--warn": "#fdb022",
  "--warn-bg": "#2a2008",
  "--warn-line": "#5c4511",
  "--shadow": "0 1px 2px rgba(0, 0, 0, 0.3), 0 6px 24px rgba(0, 0, 0, 0.35)",
};

function brandVars(primary, palette, dark) {
  const card = palette["--card"];
  const onBrand = contrast(primary, "#ffffff") >= contrast(primary, "#17212b") ? "#ffffff" : "#17212b";
  return {
    "--on-brand": onBrand,
    "--brand-600": dark ? mix(primary, "#ffffff", 0.88) : mix(primary, "#000000", 0.9),
    "--brand-50": mix(primary, card, dark ? 0.18 : 0.1),
    "--brand-100": mix(primary, card, dark ? 0.32 : 0.2),
    "--brand-ink": readable(primary, card, dark ? "#ffffff" : "#000000"),
  };
}

const decls = (vars, indent) => Object.entries(vars).map(([k, v]) => `${indent}${k}: ${v};`).join("\n");

function cssBlock(b) {
  const base = { "--font": b.font, "--brand": b.primary, "--accent": b.accent };
  const light = { ...base, ...brandVars(b.primary, LIGHT, false), ...LIGHT };
  const dark = { ...base, ...brandVars(b.primary, DARK, true), ...DARK };
  const lines = [START];
  if (b.theme === "dark") lines.push(":root {", "  color-scheme: dark;", decls(dark, "  "), "}");
  else lines.push(":root {", `  color-scheme: ${b.theme === "auto" ? "light dark" : "light"};`, decls(light, "  "), "}");
  if (b.theme === "auto") lines.push("@media (prefers-color-scheme: dark) {", "  :root {", decls(dark, "    "), "  }", "}");
  lines.push(END);
  return lines.join("\n");
}

// ---------- html ----------
const escHtml = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const logoType = (url) => (url.endsWith(".png") ? "image/png" : "image/svg+xml");

function themeColors(theme) {
  if (theme === "light") return [[LIGHT["--bg"], null]];
  if (theme === "dark") return [[DARK["--bg"], null]];
  return [
    [LIGHT["--bg"], "(prefers-color-scheme: light)"],
    [DARK["--bg"], "(prefers-color-scheme: dark)"],
  ];
}

function rewriteHtml(src, oldName, b) {
  let s = src;
  // Product name, as a whole word (so "Slot" never rewrites "Slotwise").
  if (oldName !== b.name) {
    const re = new RegExp(`(?<![A-Za-z0-9])${escRe(escHtml(oldName))}(?![A-Za-z0-9])`, "g");
    s = s.replace(re, () => escHtml(b.name));
  }
  s = s.replace(/\/assets\/logo\.(svg|png)/g, b.logo);
  s = s.replace(/(<link rel="icon" href="[^"]*" type=")[^"]*(")/g, `$1${logoType(b.logo)}$2`);
  // theme-color meta tags: drop any, then insert the current ones after the viewport tag.
  s = s.replace(/^[ \t]*<meta name="theme-color"[^>]*>\r?\n/gm, "");
  s = s.replace(/^([ \t]*)<meta name="viewport"[^>]*?(\s?\/?)>\r?\n/m, (line, indent, close) => {
    const tags = themeColors(b.theme).map(
      ([c, media]) => `${indent}<meta name="theme-color" content="${c}"${media ? ` media="${media}"` : ""}${close}>\n`,
    );
    return line + tags.join("");
  });
  return s;
}

function defaultLogo(b) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="${escHtml(b.name)}">
  <rect x="2" y="2" width="60" height="60" rx="16" fill="${b.primary}"/>
  <rect x="14" y="18" width="36" height="10" rx="5" fill="#ffffff" opacity="0.55"/>
  <rect x="14" y="36" width="24" height="10" rx="5" fill="#ffffff"/>
  <circle cx="45" cy="41" r="5" fill="${b.accent}"/>
</svg>
`;
}

// ---------- main ----------
const args = parseArgs();
if (args.help) {
  const lines = readFileSync(fileURLToPath(import.meta.url), "utf8").split("\n").slice(1);
  const header = lines.slice(0, lines.findIndex((l) => !l.startsWith("//")));
  process.stdout.write(`${header.map((l) => l.replace(/^\/\/ ?/, "")).join("\n")}\n`);
  process.exit(0);
}
if (!existsSync(BRAND_FILE)) fail(`missing ${BRAND_FILE}`);
const current = JSON.parse(readFileSync(BRAND_FILE, "utf8"));
const changing = KNOWN.some((k) => k in args);
if (!changing && !args.apply) {
  process.stdout.write(`${JSON.stringify(current, null, 2)}\n`);
  process.exit(0);
}

const next = {
  name: current.name,
  primary: current.primary,
  accent: current.accent,
  logo: current.logo ?? DEFAULT_LOGO,
  customLogo: current.customLogo ?? false,
  theme: current.theme ?? "light",
  font: current.font,
};
if ("name" in args) next.name = args.name;
next.name = String(next.name ?? "").trim();
if (!next.name || next.name.length > 60 || /[\u0000-\u001f]/.test(next.name)) fail("--name must be 1 to 60 printable characters");
next.primary = normHex("primary" in args ? args.primary : next.primary, "primary");
next.accent = normHex("accent" in args ? args.accent : next.accent, "accent");
if ("theme" in args) next.theme = args.theme;
if (!THEMES.includes(next.theme)) fail(`--theme must be one of ${THEMES.join(", ")}`);
if ("font" in args) next.font = args.font;
next.font = String(next.font ?? "").trim();
if (!next.font || /[;{}<>\\]|\/\*|\*\//.test(next.font)) fail("--font must be a CSS font stack without ; { } < > or comments");

let logoSource = null;
if ("logo" in args) {
  if (args.logo === "default") {
    next.logo = DEFAULT_LOGO;
    next.customLogo = false;
  } else {
    logoSource = resolve(process.cwd(), args.logo);
    const ext = extname(logoSource).toLowerCase();
    if (!LOGO_EXTS.includes(ext)) fail("--logo must be an .svg or .png file (or 'default')");
    if (!existsSync(logoSource)) fail(`logo file not found: ${args.logo}`);
    next.logo = `/assets/logo${ext}`;
    next.customLogo = true;
  }
}

// The name currently applied to the HTML is the <title> of the SPA shell, so a hand-edited brand.json still works.
const indexSrc = readFileSync(INDEX_HTML, "utf8");
const titleMatch = /<title>([^<]*)<\/title>/.exec(indexSrc);
const appliedName = titleMatch ? titleMatch[1].replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&") : current.name;

const writes = new Map(); // path -> string | Buffer
const removes = [];

writes.set(BRAND_FILE, `${JSON.stringify(next, null, 2)}\n`);

const css = readFileSync(CSS_FILE, "utf8");
const si = css.indexOf(START);
const ei = css.indexOf(END);
if (si < 0 || ei < si) fail(`${CSS_FILE} has no brand block (${START} ... ${END})`);
writes.set(CSS_FILE, css.slice(0, si) + cssBlock(next) + css.slice(ei + END.length));

const logoFile = join(ASSETS, next.logo.replace(/^\/assets\//, ""));
if (logoSource) writes.set(logoFile, readFileSync(logoSource));
else if (!next.customLogo) writes.set(logoFile, defaultLogo(next));
for (const ext of LOGO_EXTS) {
  const f = join(ASSETS, `logo${ext}`);
  if (f !== logoFile && existsSync(f)) removes.push(f);
}

const htmlFiles = [INDEX_HTML, ...readdirSync(STATIC_DIR).filter((f) => f.endsWith(".html")).sort().map((f) => join(STATIC_DIR, f))];
for (const f of htmlFiles) writes.set(f, rewriteHtml(readFileSync(f, "utf8"), appliedName, next));

const rel = (p) => p.slice(ROOT.length + 1);
const changed = [];
for (const [f, content] of writes) {
  const before = existsSync(f) ? readFileSync(f) : null;
  const after = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (!before || !before.equals(after)) changed.push(f);
}

if (args["dry-run"]) {
  process.stdout.write(`${JSON.stringify(next, null, 2)}\n`);
  process.stdout.write(`dry run: would update ${changed.length} file(s)${changed.length ? `: ${changed.map(rel).join(", ")}` : ""}`);
  process.stdout.write(`${removes.length ? `; would remove ${removes.map(rel).join(", ")}` : ""}\n`);
  process.exit(0);
}
for (const f of changed) writeFileSync(f, writes.get(f));
for (const f of removes) rmSync(f);
process.stdout.write(`${JSON.stringify(next, null, 2)}\n`);
process.stdout.write(`updated ${changed.length} file(s)${changed.length ? `: ${changed.map(rel).join(", ")}` : ""}${removes.length ? `; removed ${removes.map(rel).join(", ")}` : ""}\n`);
if (changed.length || removes.length) process.stdout.write("Run `npm run build` so the web bundle and server use the new brand.\n");
